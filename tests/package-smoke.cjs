'use strict';
// Run with this project's development dependencies against an independently extracted delivery.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
  const root=path.resolve(process.argv[2]||path.join(__dirname,'..'));
  const url=pathToFileURL(path.join(root,'index.html')).href;
  const browser=await chromium.launch({channel:'chrome'});
  const page=await browser.newPage({viewport:{width:1920,height:1080},offline:true});
  const errors=[],remote=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(/^https?:/.test(r.url()))remote.push(r.url());});
  try {
    await page.goto(url);
    await page.waitForSelector('.landscape-canvas.ready');
    assert.match(await page.locator('#slide-title').innerText(),/大连市自然资源/);
    await page.locator('#pause-button').click();
    const a=await page.locator('.landscape-canvas').getAttribute('data-frame');
    await page.waitForTimeout(250);assert.equal(await page.locator('.landscape-canvas').getAttribute('data-frame'),a);
    await page.goto(url+'#p22');
    await page.getByRole('button',{name:'政策文件',exact:true}).click();
    assert.equal(await page.locator('.gallery-spread .image-button').count(),1);
    await page.waitForFunction(()=>[...document.querySelectorAll('.gallery-spread img')].every(i=>i.complete&&i.naturalWidth>0));
    assert.equal(await page.locator('#sources-button,#sources-dialog').count(),0);
    await page.keyboard.press('End');assert.equal(await page.locator('#page-count').innerText(),'31 / 31');
    await page.mouse.move(0,0);
    await page.goto(url+'#p5');
    const manual=page.getByRole('button',{name:'固定查看：中标通知书',exact:true});await manual.waitFor();
    assert.equal(await page.locator('#play-button').isDisabled(),true);
    const before=await manual.boundingBox();await manual.hover();await page.waitForTimeout(450);
    assert((await manual.boundingBox()).width>before.width*1.2);
    await manual.click();await page.locator('#slide-title').hover();
    assert.equal(await manual.getAttribute('aria-pressed'),'true');
    await page.getByRole('button',{name:'恢复全览',exact:true}).click();
    assert.equal(await manual.getAttribute('aria-pressed'),'false');
    await page.goto(url+'#p4');
    const policy=page.getByRole('button',{name:'《辽宁省自然资源统一确权登记工作总体方案》',exact:true});await policy.waitFor();
    assert.equal(await page.locator('#play-button').isDisabled(),true);
    assert((await page.locator('.policy-directory').boundingBox()).width>=700);
    await policy.hover();await policy.click();await page.locator('#slide-title').hover();
    assert.match(await page.locator('.policy-choice[aria-current="true"] .policy-choice-name').innerText(),/辽宁省/);
    assert.equal(await policy.getAttribute('aria-pressed'),'true');
    await page.getByRole('button',{name:'恢复默认',exact:true}).click();
    assert.match(await page.locator('.policy-choice[aria-current="true"] .policy-choice-name').innerText(),/确权登记规程/);
    assert.equal(await page.locator('.policy-page-title,.policy-page-meta,.policy-reader-hint').count(),0);
    await page.goto(url);
    await page.waitForSelector('#slide-title');
    assert.match(await page.title(),/^RiverAtlas ·/);
    await page.locator('#starfield').waitFor();
    await page.goto(url+'#p3');await page.locator('.leaflet-container').waitFor();
    assert.equal(await page.locator('.river-flow').count(),5);
    await page.getByRole('button',{name:'英那河 庄河市',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'英那河 庄河市',exact:true}).getAttribute('aria-pressed'),'true');
    await page.getByRole('button',{name:'全部 五条河流总览',exact:true}).click();
    await page.goto(url+'#p8');
    assert.equal(await page.locator('.document-board img').count(),1);
    await page.locator('.document-board .image-button').click();
    await page.waitForFunction(()=>{const i=document.getElementById('original-image');return !i.hidden&&i.complete&&i.naturalWidth>0;});
    assert.match(await page.locator('#image-title').innerText(),/工作底图/);
    await page.keyboard.press('Escape');
    await page.goto(url+'#p2');assert.equal(await page.locator('.document-board img').count(),2);
    await page.goto(url+'#p6');assert.equal(await page.locator('.workflow-phase').count(),3);
    await page.goto(url+'#p17');assert.equal(await page.locator('.database-category').count(),5);
    await page.goto(url+'#p20');assert.equal(await page.locator('.staff-seat').count(),23);
    await page.goto(url+'#p30');assert.equal(await page.locator('.gallery-tabs button').count(),6);
    await page.locator('.gallery-tabs button').last().click();
    await page.waitForFunction(()=>{const i=document.querySelector('.gallery-spread img');return i.complete&&i.naturalWidth>0;});
    assert.equal(await page.locator('.gallery-spread img').getAttribute('data-asset'),'106');
    await page.goto(url+'#p16');assert.equal(await page.locator('.gallery-tabs button').count(),3);
    await page.locator('.gallery-tabs button').last().click();assert.match(await page.locator('.gallery-caption').innerText(),/水流资源/);
    await page.goto(url+'#p19');assert.equal(await page.locator('.document-board .image-button').count(),1);
    assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
    console.log(JSON.stringify({deliveryRoot:root,offline:true,singleEntry:true,geographicMap:true,starfield:true,pairedDocuments:true,basemap:true,webgl:true,policies:2,sourcePages:41,presentationPages:31,businessImages:40,staff:23,originalOpened:true,navigation:true,manualSample:true,manualPolicy:true,remoteRequests:0,pageErrors:0}));
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
